<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property int $candidate_id
 * @property int $job_id
 * @property string $input_hash
 * @property array<string, mixed> $result
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable(['candidate_id', 'job_id', 'input_hash', 'result'])]
class Analysis extends Model
{
    /**
     * Exact wording injected server-side into every analysis result. Never generated by the model.
     */
    public const FAIRNESS_NOTE = 'No protected attributes (age, gender, ethnicity, nationality, religion) were used in this assessment.';

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'result' => 'array',
        ];
    }

    /**
     * @return BelongsTo<Candidate, $this>
     */
    public function candidate(): BelongsTo
    {
        return $this->belongsTo(Candidate::class);
    }

    /**
     * @return BelongsTo<JobOpening, $this>
     */
    public function jobOpening(): BelongsTo
    {
        return $this->belongsTo(JobOpening::class, 'job_id');
    }
}
